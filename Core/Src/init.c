#include "init.h"

void System_Init(void) {
    // 1. Включаем тактирование порта GPIOB
    RCC->AHB1ENR |= RCC_AHB1ENR_GPIOBEN;

    // 2. Настройка пинов PB6, PB8, PB9 как выходы (светодиоды 2, 3, 4)
    // Очищаем биты конфигурации MODER для пинов 6, 8, 9
    GPIOB->MODER &= ~((3U << (2 * 6)) | (3U << (2 * 8)) | (3U << (2 * 9)));
    // Устанавливаем режим выхода (01)
    GPIOB->MODER |=  ((1U << (2 * 6)) | (1U << (2 * 8)) | (1U << (2 * 9)));

    // 3. Настройка пина PB5 как вход с подтяжкой к питанию (Кнопка 2)
    GPIOB->MODER &= ~(3U << (2 * 5)); // Режим входа (00)
    GPIOB->PUPDR &= ~(3U << (2 * 5)); 
    GPIOB->PUPDR |=  (1U << (2 * 5)); // Pull-up (01)

    // 4. Пин PB2 (Кнопка 1 + Светодиод 1) по умолчанию настраивается как вход с подтяжкой
    GPIOB->MODER &= ~(3U << (2 * 2)); // Вход
    GPIOB->PUPDR &= ~(3U << (2 * 2));
    GPIOB->PUPDR |=  (1U << (2 * 2)); // Pull-up
}